// Regenerates src/abi.ts from the Foundry build output (run `forge build` in ../contracts first).
import { readFileSync, writeFileSync } from "node:fs";

const names = ["RodaFactory", "RodaCircle", "RodaReputation", "TestDollar"];
const out = names
  .map((n) => {
    const { abi } = JSON.parse(readFileSync(new URL(`../../contracts/out/${n}.sol/${n}.json`, import.meta.url)));
    const id = n[0].toLowerCase() + n.slice(1);
    return `export const ${id}Abi = ${JSON.stringify(abi)} as const;`;
  })
  .join("\n\n");
writeFileSync(new URL("../src/abi.ts", import.meta.url), `// Generated by scripts/abi.mjs. Do not edit.\n${out}\n`);
